export type MessageKey = keyof typeof messages;
export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return messages[key][languages.indexOf(language)].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

export function translateError(language: Language, message: string): string {
  if (message === 'ESSAY_MISSING') return translate(language, 'essayMissing');
  if (message.includes('50 万字符')) return translate(language, 'tooLong');
  if (message.includes('12 MB')) return translate(language, 'tooLarge');
  if (message.includes('修改记录过多')) return translate(language, 'tooMany');
  if (/文件内容无效|文件格式或版本|不是有效的练习|草稿不能|Unexpected token|JSON/.test(message))
    return translate(language, 'invalidFile');
  if (
    /位置无效|内容无效|选区不匹配|原文不匹配|编号重复|已有修改|已有添加|修改记录无效/.test(message)
  )
    return translate(language, 'invalidEdit');
  return message;
}
